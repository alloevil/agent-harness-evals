PIPELINE = ("pip install -r requirements.txt && python src/fetch.py && python src/normalize.py && "
            "python src/views_harness.py")


def claims(payload: dict) -> dict:
    """Every value is read off the payload the page was built from, so claims.json cannot drift from the site.

    These are aggregations of third-party leaderboard scores, not measurements taken here; each `method` says so.
    """
    t = payload["totals"]
    day = payload["updated"]
    matrices = _matrices(payload)
    aggregation = ("aggregation of published leaderboard scores (Epoch AI Benchmarking Hub, HAL): best published score "
                   "per (model, harness) pair; no evaluation is run by this project")
    normalization = ("third-party leaderboard scores fetched from the Epoch AI Benchmarking Hub and the HAL "
                     "leaderboards and normalized into one record schema; no evaluation is run by this project")

    def claim(cid: str, text: str, value: str, metric: str, method: str, repro: str, evidence: str) -> dict:
        return {"id": cid, "claim": text, "value": value, "metric": metric, "method": method,
                "repro": repro, "evidence": evidence, "verified": day}

    items = [
        claim(
            "records-reconciled",
            f"{t['records']} leaderboard records across {t['benchmarks']} benchmarks are normalized into one "
            "(benchmark, model, harness, score) schema.",
            str(t["records"]),
            "rows in data/clean/records.parquet after model and harness name reconciliation",
            normalization + "; model ids are canonicalized so the same model from two sources joins instead of forking",
            PIPELINE,
            f"{REPO}/tree/master/data/snapshots",
        ),
        claim(
            "cross-harness-coverage",
            f"{t['models']} models and {t['harnesses']} harnesses appear in at least one cross-harness matrix, over "
            f"{len(matrices)} benchmarks.",
            f"{t['models']} models x {t['harnesses']} harnesses",
            "distinct models and harnesses on boards where a model was measured under 2 or more harnesses",
            aggregation + "; models measured under a single harness are excluded from the matrix",
            PIPELINE,
            f"{REPO}/tree/master/views",
        ),
    ]
    for bench, b in matrices.items():
        spread = b["summary"].get("medianSpread")
        if spread is None:
            continue  # no model on this board has 3+ harnesses: a 2-harness gap is one difference, not a spread
        items.append(
            claim(
                f"median-harness-spread-{bench}",
                f"On {b['name']}, the median gap between a model's best and worst agent harness is {spread} "
                f"(score as a 0-1 rate), across {b['summary']['spreadModels']} models measured under 3 or more harnesses.",
                str(spread),
                "median over models with 3+ harnesses of (best harness score - worst harness score) for that model",
                aggregation + "; models with fewer than 3 harnesses are excluded because a 2-harness gap is a single "
                "pairwise difference",
                PIPELINE,
                f"{REPO}/blob/master/views/harness_matrix_{bench}.md",
            )
        )
    return {"project": "agent-harness-evals", "url": f"{SITE}/", "repository": REPO, "updated": day, "claims": items}


