def robots_txt() -> str:
    return f"User-agent: *\nAllow: /\n\nSitemap: {SITE}/sitemap.xml\n"


def sitemap_xml() -> str:
    """Every HTML page actually present in docs/, home as the trailing-slash directory URL.

    Enumerated from disk rather than hand-listed: a sitemap written by hand next to a generated
    site drifts the moment a page is added or dropped.
    """
    pages = sorted(p.name for p in DOCS.glob("*.html"))
    locs = [f"{SITE}/"] + [f"{SITE}/{name}" for name in pages if name != "index.html"]
    entries = "".join(f"  <url><loc>{loc}</loc></url>\n" for loc in locs)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            f"{entries}</urlset>\n")


def build_site(payload: dict | None = None) -> Path:
    DOCS.mkdir(exist_ok=True)
    payload = payload or build_payload()
    html = (TEMPLATE.replace("__JSONLD__", json_ld(payload))
            .replace("__DATA__", json.dumps(payload, separators=(",", ":"))))
    dest = DOCS / "index.html"
    dest.write_text(html)
    (DOCS / "llms.txt").write_text(llms_txt(payload))
    (DOCS / "llms-full.txt").write_text(llms_full_txt(payload))
    (DOCS / "claims.json").write_text(json.dumps(claims(payload), ensure_ascii=False, indent=2) + "\n")
    (DOCS / "robots.txt").write_text(robots_txt())
    (DOCS / "sitemap.xml").write_text(sitemap_xml())
    print(f"site: {dest} ({dest.stat().st_size/1024:.0f} KB, "
          f"{len(payload['benchmarks'])} benchmark tabs) + robots.txt, sitemap.xml, llms.txt, llms-full.txt, claims.json")
    return dest


