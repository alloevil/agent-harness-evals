"""Build the static site: docs/index.html, self-contained (data inlined), plus the
machine-readable retrieval artifacts docs/llms.txt, docs/llms-full.txt and
docs/claims.json.

One page, no build step, no dependencies at serve time. Regenerated by the
same pipeline run that refreshes the data, so the page is never staler than
the parquet — and the JSON-LD, the llms files and every number in claims.json
are derived from the same payload, so they cannot disagree with the page.

Information architecture: conclusions first. Every benchmark opens with the
answer strip (best pairing, best harness, median spread), then three views —
the model × harness matrix, a harness ranking, and a model ranking — so
"which harness / which model / which combo" each take one glance, not a
scan of a 30×37 table.
"""
from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parent.parent
CLEAN = ROOT / "data" / "clean" / "records.parquet"
DOCS = ROOT / "docs"
META = Path(__file__).resolve().parent / "benchmarks.yaml"

SITE = "https://alloevil.github.io/agent-harness-evals"
REPO = "https://github.com/alloevil/agent-harness-evals"

MIN_HARNESSES = 2


def _bench_meta() -> dict:
    return yaml.safe_load(META.read_text()) or {}


def build_payload() -> dict:
    records = pd.read_parquet(CLEAN)
    meta = _bench_meta()
    scaffolded = records[(records["scaffold"] != "") & (records["score_unit"] == "rate")]
    benches = {}
    for bench, grp in scaffolded.groupby("benchmark"):
        cell = grp.groupby(["model", "scaffold"])["score"].max().reset_index()
        counts = cell.groupby("model")["scaffold"].nunique()
        cell = cell[cell["model"].isin(counts[counts >= MIN_HARNESSES].index)]
        released = grp.groupby("model")["release_date"].first()
        info = meta.get(bench, {})
        if cell.empty:
            # Native-pairing board: several harnesses on the leaderboard, but
            # each model tested only under one (typically its vendor's CLI).
            # No cross-harness comparison exists, but the model×native-harness
            # ranking is real signal — don't hide it.
            best = (grp.groupby(["model", "scaffold"])["score"].max()
                    .reset_index().sort_values("score", ascending=False))
            best = best.loc[best.groupby("model")["score"].idxmax()]
            best = best.sort_values("score", ascending=False)
            if grp["scaffold"].nunique() < 2 or len(best) < 5:
                continue
            top = best.iloc[0]
            benches[bench] = {
                "name": info.get("name", bench),
                "blurb": info.get("blurb", ""),
                "link": info.get("link", ""),
                "native": True,
                "released": {m: (None if pd.isna(d) else str(d)[:10])
                             for m, d in released.items()},
                "models": list(best["model"]),
                "harnesses": sorted(grp["scaffold"].unique()),
                "modelRank": [[r["model"], round(float(r["score"]), 3), r["scaffold"]]
                              for _, r in best.iterrows()],
                "summary": {"bestCombo": [top["model"], top["scaffold"],
                                          round(float(top["score"]), 3)]},
            }
            continue
        matrix = cell.pivot(index="model", columns="scaffold", values="score")
        matrix = matrix.loc[matrix.max(axis=1).sort_values(ascending=False).index]
        matrix = matrix[matrix.notna().sum().sort_values(ascending=False).index]

        # --- summary + rankings: the "answer first" layer -------------------
        row_max = matrix.max(axis=1)
        rel = matrix.div(row_max, axis=0)          # cell / model's best
        n_models = matrix.notna().sum()            # models per harness
        mean_rel = rel.mean()                      # avg share of model-best kept
        wins = rel.eq(1.0).sum()                   # models for which it's the best
        harness_rank = sorted(
            ([h, int(n_models[h]), round(float(mean_rel[h]), 3), int(wins[h])]
             for h in matrix.columns if n_models[h] >= 2),
            # Trustworthy sample first, then effectiveness: a 2-model harness
            # never outranks a 3+-model one just by a lucky pair.
            key=lambda r: (-(r[1] >= 3), -r[2], -r[1]),
        )

        spread = row_max - matrix.min(axis=1)
        n_row = matrix.notna().sum(axis=1)
        model_rank = [
            [m, round(float(row_max[m]), 3), matrix.loc[m].idxmax(),
             round(float(spread[m]), 3), int(n_row[m])]
            for m in matrix.index
        ]

        best_m = row_max.idxmax()
        best_combo = [best_m, matrix.loc[best_m].idxmax(), round(float(row_max[best_m]), 3)]
        # Headline harness: [name, meanRel, nModels]. The ranking table keeps
        # everything (dimmed below n=3); the headline tile takes the best
        # harness at the largest sample tier that exists (5+, then 3+, then 2).
        top = None
        for tier in (5, 3, 2):
            tiered = [r for r in harness_rank if r[1] >= tier]
            if tiered:
                top = max(tiered, key=lambda r: r[2])
                break
        best_harness = [top[0], top[2], top[1]] if top else None
        reliable = spread[n_row >= 3]
        benches[bench] = {
            "name": info.get("name", bench),
            "blurb": info.get("blurb", ""),
            "link": info.get("link", ""),
            "harnesses": list(matrix.columns),
            "hcov": [int(n_models[h]) for h in matrix.columns],
            "models": list(matrix.index),
            "n": n_row.tolist(),
            "released": {m: (None if pd.isna(d) else str(d)[:10])
                         for m, d in released.items()},
            "rows": [[None if pd.isna(v) else round(float(v), 3) for v in row]
                     for row in matrix.to_numpy()],
            "summary": {
                "bestCombo": best_combo,
                "bestHarness": best_harness,
                "medianSpread": (round(float(reliable.median()), 3)
                                 if len(reliable) else None),
                "spreadModels": int(len(reliable)),
            },
            "harnessRank": harness_rank,
            "modelRank": model_rank,
        }
    # Cross-harness matrices first (the project's point), native boards after;
    # richest first within each group.
    benches = dict(sorted(benches.items(),
                          key=lambda kv: (kv[1].get("native", False),
                                          -len(kv[1]["models"]) * len(kv[1]["harnesses"]))))
    multi_models = {m for b in benches.values() if not b.get("native") for m in b["models"]}
    multi_harn = {h for b in benches.values() if not b.get("native") for h in b["harnesses"]}
    return {
        "updated": date.today().isoformat(),
        "totals": {"records": len(records), "benchmarks": int(records["benchmark"].nunique()),
                   "models": len(multi_models), "harnesses": len(multi_harn)},
        "benchmarks": benches,
    }


